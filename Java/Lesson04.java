// - 引き算
// * 掛け算
// / 割り算
// % 余剰（あまり）

// 関係演算子  二つの値が正しかを比較する

class Lesson04 {
  public static void main(String[] args) {
    int x = 10;
    int y = 2;
    int z = 10;

    System.out.println(x + y);
    System.out.println(x - y);
    System.out.println(x * y);
    System.out.println(x / y);
    System.out.println(x % y);

    System.out.println(x < y);
    System.out.println(x > y);
  }
}